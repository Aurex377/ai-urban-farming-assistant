BOTANICAL_CATALOG_DICT: Dict[str, Dict[str, Any]] = {p["id"]: p for p in BOTANICAL_CATALOG}


def get_catalog_plant_by_id(plant_id: str) -> Optional[Dict[str, Any]]:
    """Finds a plant record in the verified botanical catalog by unique ID or alias."""
    if not plant_id:
        return None
    if plant_id in BOTANICAL_CATALOG_DICT:
        return BOTANICAL_CATALOG_DICT[plant_id]
    
    # Case-insensitive or normalized check
    target = plant_id.lower().replace("-", "_").replace(" ", "_")
    for pid, plant in BOTANICAL_CATALOG_DICT.items():
        if pid.lower() == target or plant.get("name", "").lower() == plant_id.lower():
            return plant
    return None
